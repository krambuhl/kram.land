import { resolveValue } from 'token-jet';
import type { ResolvedTokens } from 'token-jet';

import type { MatchOptions } from './index.ts';

const DEFAULT_TAG = 'media-breakpoint';

export interface Scale {
  names: string[];
  widths: string[];
}

export function scaleFromTokens(resolved: ResolvedTokens, tag = DEFAULT_TAG): Scale {
  const tokens = resolved.tokens.filter((t) => t.tags?.includes(tag));
  if (tokens.length === 0) throw new Error(`No tokens carry the tag "${tag}", so there are no breakpoints.`);
  return {
    names: tokens.map((t) => t.segments[t.segments.length - 1]),
    widths: tokens.map((t) => String(resolveValue(t.path, resolved.tokens))),
  };
}

function indexOf(scale: Scale, name: string): number {
  const index = scale.names.indexOf(name);
  if (index < 0) throw new Error(`"${name}" is not a breakpoint. Breakpoints are ${scale.names.join(', ')}.`);
  return index;
}

export function rangeOf(match: MatchOptions, scale: Scale): [from: number, to: number] {
  const last = scale.names.length - 1;
  if (match.matchMin !== undefined) return [indexOf(scale, match.matchMin), last];
  if (match.matchMax !== undefined) return [0, indexOf(scale, match.matchMax)];
  const only: readonly string[] = typeof match.matchOnly === 'string' ? [match.matchOnly] : match.matchOnly;
  if (only.length === 0) throw new Error('matchOnly needs at least one breakpoint.');
  const indexes = only.map((name) => indexOf(scale, name));
  for (let i = 1; i < indexes.length; i++) {
    if (indexes[i] !== indexes[i - 1] + 1) {
      throw new Error(`matchOnly [${only.join(', ')}] is not a contiguous run of ${scale.names.join(', ')}.`);
    }
  }
  return [indexes[0], indexes[indexes.length - 1]];
}

export function mediaQuery([from, to]: [number, number], scale: Scale): string | null {
  const lower = from > 0 ? scale.widths[from] : null;
  const upper = to < scale.names.length - 1 ? scale.widths[to + 1] : null;
  if (lower !== null && upper !== null) return `(${lower} <= width < ${upper})`;
  if (lower !== null) return `(width >= ${lower})`;
  if (upper !== null) return `(width < ${upper})`;
  return null;
}

export function typesFile(scale: Scale): string {
  const quote = (name: string) => `'${name}'`;
  const ranges: string[] = [];
  for (let from = 0; from < scale.names.length; from++) {
    for (let to = from; to < scale.names.length; to++) {
      ranges.push(
        `readonly [${scale.names
          .slice(from, to + 1)
          .map(quote)
          .join(', ')}]`
      );
    }
  }
  return [
    '// generated by token-jet-responsive-css-modules. do not edit.',
    "declare module 'token-jet-responsive-css-modules' {",
    '  interface ResponsiveRegister {',
    `    breakpoint: ${scale.names.map(quote).join(' | ')};`,
    `    range: ${ranges.join(' | ')};`,
    '  }',
    '}',
    '',
    'export {};',
    '',
  ].join('\n');
}
