import type { MatchOptions } from './index.ts';

export interface Breakpoint {
  name: string;
  width: string;
}

export interface BreakpointSource {
  load(root: string): readonly Breakpoint[] | Promise<readonly Breakpoint[]>;
  watch?: string;
}

export interface Scale {
  names: string[];
  widths: string[];
}

export function toScale(breakpoints: readonly Breakpoint[]): Scale {
  if (breakpoints.length === 0) throw new Error('There are no breakpoints.');
  const names = breakpoints.map((b) => b.name);
  const repeated = names.find((name, i) => names.indexOf(name) !== i);
  if (repeated !== undefined) throw new Error(`The breakpoint "${repeated}" is listed twice.`);
  return { names, widths: breakpoints.map((b) => b.width) };
}

function indexOf(scale: Scale, name: string): number {
  const index = scale.names.indexOf(name);
  if (index < 0) throw new Error(`"${name}" is not a breakpoint. Breakpoints are ${scale.names.join(', ')}.`);
  return index;
}

export type Range = [from: number, to: number];

export function rangesOf(match: MatchOptions, scale: Scale): Range[] {
  const last = scale.names.length - 1;
  if (match.matchMin !== undefined) return [[indexOf(scale, match.matchMin), last]];
  if (match.matchMax !== undefined) return [[0, indexOf(scale, match.matchMax)]];
  const only: readonly string[] = typeof match.matchOnly === 'string' ? [match.matchOnly] : match.matchOnly;
  if (only.length === 0) throw new Error('matchOnly needs at least one breakpoint.');
  const indexes = [...new Set(only.map((name) => indexOf(scale, name)))].sort((a, b) => a - b);
  const ranges: Range[] = [];
  for (const index of indexes) {
    const previous = ranges.at(-1);
    if (previous !== undefined && previous[1] === index - 1) previous[1] = index;
    else ranges.push([index, index]);
  }
  return ranges;
}

function rangeQuery([from, to]: Range, scale: Scale): string | null {
  const lower = from > 0 ? scale.widths[from] : null;
  const upper = to < scale.names.length - 1 ? scale.widths[to + 1] : null;
  if (lower !== null && upper !== null) return `(${lower} <= width < ${upper})`;
  if (lower !== null) return `(width >= ${lower})`;
  if (upper !== null) return `(width < ${upper})`;
  return null;
}

export function mediaQuery(ranges: readonly Range[], scale: Scale): string | null {
  const queries = ranges.map((range) => rangeQuery(range, scale));
  return queries.includes(null) ? null : queries.join(', ');
}

export function typesFile(scale: Scale): string {
  const quote = (name: string) => `'${name}'`;
  return [
    '// generated by responsive-css-modules. do not edit.',
    "declare module 'responsive-css-modules' {",
    '  interface ResponsiveRegister {',
    `    breakpoint: ${scale.names.map(quote).join(' | ')};`,
    '  }',
    '}',
    '',
    'export {};',
    '',
  ].join('\n');
}
